"""Tests ported from upstream PDFBox 3.0 (3.0.9-SNAPSHOT)
``fontbox/src/test/java/org/apache/fontbox/ttf/GoldenHintingTest.java``.

Golden test comparing the FontBox interpreter's grid-fitted glyph points
against a FreeType reference dump (same font, glyph and ppem). The
reference lives in ``tests/fixtures/fontbox/ttf/hinting/<font>-<ppem>.txt``,
produced offline by upstream's ``generate_golden.py``; FreeType is never a
build or runtime dependency.

The reference is generated by FreeType 2.13.2 with the grayscale target
(``FT_LOAD_TARGET_NORMAL``), i.e. the v40 "minimal" subpixel interpreter
with backward compatibility. Coordinates are integer F26Dot6 (64 units per
pixel), so any difference at all - even 1/64 px - fails, and the message
names the worst point.
"""

from dataclasses import dataclass, field
from pathlib import Path

from pypdfbox.fontbox.ttf import TTFParser
from pypdfbox.fontbox.ttf.glyph_hinter import GlyphHinter

_TTF = Path(__file__).resolve().parents[3] / "fixtures" / "fontbox" / "ttf"
PPEMS = (11, 13, 16, 24)


@dataclass
class _GoldenGlyph:
    gid: int
    ch: str
    x: list[int] = field(default_factory=list)
    y: list[int] = field(default_factory=list)


@dataclass
class _Stats:
    compared: int = 0
    max_dx: int = 0
    max_dy: int = 0
    worst: int = 0
    worst_where: str = "none"

    def record_glyph(self, g: _GoldenGlyph, ppem: int, points: list[list[int]]) -> None:
        for i in range(len(g.x)):
            self.compared += 1
            dx = abs(points[0][i] - g.x[i])
            dy = abs(points[1][i] - g.y[i])
            self.max_dx = max(self.max_dx, dx)
            self.max_dy = max(self.max_dy, dy)
            if max(dx, dy) > self.worst:
                self.worst = max(dx, dy)
                self.worst_where = (
                    f"'{g.ch}' (gid {g.gid}) point {i} @{ppem}ppem: "
                    f"ours=({points[0][i]},{points[1][i]}) freetype=({g.x[i]},{g.y[i]})"
                )

    def summary(self, kind: str) -> str:
        return (
            f"{kind}: compared {self.compared} coords; maxDx={self.max_dx}/64 "
            f"maxDy={self.max_dy}/64; worst at {self.worst_where}"
        )


def _parse_ints(s: str) -> list[int]:
    return [int(t) for t in s.split(" ")] if s else []


def _load_golden(path: Path) -> list[_GoldenGlyph]:
    glyphs: list[_GoldenGlyph] = []
    current: _GoldenGlyph | None = None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("glyph "):
            parts = line.split(" ")
            current = _GoldenGlyph(int(parts[1]), parts[2])
            glyphs.append(current)
        elif line.startswith("x ") and current is not None:
            current.x = _parse_ints(line[2:])
        elif line.startswith("y ") and current is not None:
            current.y = _parse_ints(line[2:])
    return glyphs


def _compare(composite: bool) -> _Stats:
    font = TTFParser().parse(_TTF / "LiberationSans-Regular.ttf")
    hinter = GlyphHinter(font)
    # pypdfbox's GlyphData description is a fontTools adapter without the instruction stream, so
    # the hinter's own upstream-shaped description stands in for GlyfCompositeDescript
    hinter._initialize()
    s = _Stats()
    for ppem in PPEMS:
        golden = _load_golden(_TTF / "hinting" / f"LiberationSans-Regular-{ppem}.txt")
        assert golden
        for g in golden:
            is_composite = font.get_glyph(g.gid).get_number_of_contours() < 0
            if is_composite != composite:
                continue
            if composite:
                # the composite's own program must run, not just its components' programs, so
                # an exact match proves the composite path rather than only the component one
                instructions = hinter._description(g.gid).get_instructions()
                assert instructions, f"golden composite '{g.ch}' has no instructions of its own"
            # None would mean the hinter gave up and the raw outline would be rendered
            points = hinter.get_hinted_points_f26_dot6(g.gid, ppem)
            assert points is not None, f"no hinted points for gid {g.gid} at {ppem}ppem"
            assert len(points[0]) == len(g.x), (
                f"point count mismatch for '{g.ch}' at {ppem}ppem: ours={len(points[0])} "
                f"freetype={len(g.x)}"
            )
            s.record_glyph(g, ppem, points)
    return s


def test_simple_glyphs_match_free_type_exactly() -> None:
    simple = _compare(False)
    assert simple.compared > 0, simple.summary("simple")
    assert simple.max_dx == 0 and simple.max_dy == 0, simple.summary("simple")


def test_composite_glyphs_match_free_type_exactly() -> None:
    """Every golden composite carries instructions of its own (checked in ``_compare``), so this
    covers the whole composite path: components hinted and assembled, then the composite
    program."""
    composite = _compare(True)
    assert composite.compared > 0, composite.summary("composite")
    assert composite.max_dx == 0 and composite.max_dy == 0, composite.summary("composite")
